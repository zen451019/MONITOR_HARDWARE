#!/usr/bin/env python3
"""Generate or import ABP device identities (CSV/JSON + firmware header)."""

import argparse
import csv
import hashlib
import json
import re
import secrets
from datetime import datetime, timezone
from pathlib import Path


def parse_int(value: str) -> int:
    return int(value, 0)


def hex_bytes(data: bytes) -> str:
    return "".join(f"{b:02X}" for b in data)


def c_array(data: bytes) -> str:
    return ", ".join(f"0x{b:02X}" for b in data)


def write_header(devices: list[dict], header_path: Path) -> None:
    lines = [
        "#ifndef MULTI_DEVICE_CONFIG_H",
        "#define MULTI_DEVICE_CONFIG_H",
        "",
        "// AUTO-GENERATED by tools/generate_abp_devices.py. Do not commit.",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "struct AbpDevice {",
        "    uint32_t dev_addr;",
        "    uint8_t nwk_s_key[16];",
        "    uint8_t app_s_key[16];",
        "};",
        "",
        "static const AbpDevice kAbpDevices[] = {",
    ]

    for d in devices:
        lines.append(
            "    {0x%08XUL, {%s}, {%s}},"
            % (
                d["dev_addr_int"],
                c_array(d["nwk_s_key_bytes"]),
                c_array(d["app_s_key_bytes"]),
            )
        )

    lines.extend(
        [
            "};",
            "",
            "static const size_t kAbpDeviceCount = sizeof(kAbpDevices) / sizeof(kAbpDevices[0]);",
            "",
            "#endif  // MULTI_DEVICE_CONFIG_H",
        ]
    )

    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_hex_key(value: str, name: str, line_no: int) -> bytes:
    cleaned = value.strip().replace(" ", "")
    if not cleaned:
        raise ValueError(f"Linea {line_no}: falta {name}")
    try:
        data = bytes.fromhex(cleaned)
    except ValueError as exc:
        raise ValueError(f"Linea {line_no}: {name} no es hexadecimal valido") from exc
    if len(data) != 16:
        raise ValueError(f"Linea {line_no}: {name} debe tener 16 bytes (32 hex)")
    return data


def read_devices_from_csv(csv_path: Path) -> list[dict]:
    devices = []
    seen_addr = set()
    seen_eui = set()

    with csv_path.open("r", newline="", encoding="utf-8-sig") as fh:
        reader = csv.DictReader(fh)
        if reader.fieldnames is None:
            raise ValueError("El CSV esta vacio o no tiene cabecera")

        fields = {f.strip() for f in reader.fieldnames if f}
        required = {"dev_addr", "nwk_s_key", "app_s_key"}
        missing = sorted(required - fields)
        if missing:
            raise ValueError("Faltan columnas en el CSV: " + ", ".join(missing))

        for line_no, raw in enumerate(reader, start=2):
            row = {}
            for key, value in raw.items():
                if key is None:
                    continue
                clean_key = key.strip()
                row[clean_key] = value.strip() if isinstance(value, str) else value

            if not any(row.values()):
                continue

            addr_raw = row.get("dev_addr", "").strip()
            if addr_raw.lower().startswith("0x"):
                addr_raw = addr_raw[2:]
            if not re.fullmatch(r"[0-9A-Fa-f]{1,8}", addr_raw):
                raise ValueError(f"Linea {line_no}: dev_addr no es hexadecimal valido")
            dev_addr = int(addr_raw, 16)
            if dev_addr in seen_addr:
                raise ValueError(f"Linea {line_no}: dev_addr duplicado ({addr_raw})")
            seen_addr.add(dev_addr)

            nwk_s_key = parse_hex_key(row.get("nwk_s_key", ""), "nwk_s_key", line_no)
            app_s_key = parse_hex_key(row.get("app_s_key", ""), "app_s_key", line_no)

            dev_eui = ""
            eui_raw = row.get("dev_eui", "").strip()
            if eui_raw:
                if eui_raw.lower().startswith("0x"):
                    eui_raw = eui_raw[2:]
                if not re.fullmatch(r"[0-9A-Fa-f]{16}", eui_raw):
                    raise ValueError(f"Linea {line_no}: dev_eui debe tener 16 hex")
                dev_eui = eui_raw.upper()
                if dev_eui in seen_eui:
                    raise ValueError(f"Linea {line_no}: dev_eui duplicado ({dev_eui})")
                seen_eui.add(dev_eui)

            for key_name in ("nwk_s_enc_key", "f_nwk_s_int_key", "s_nwk_s_int_key"):
                key_raw = row.get(key_name, "").strip()
                if not key_raw:
                    continue
                candidate = parse_hex_key(key_raw, key_name, line_no)
                if candidate != nwk_s_key:
                    raise ValueError(
                        f"Linea {line_no}: {key_name} no coincide con nwk_s_key "
                        "(el firmware usa LoRaWAN 1.0.x)"
                    )

            devices.append(
                {
                    "index": len(devices),
                    "dev_eui": dev_eui,
                    "dev_addr": f"{dev_addr:08X}",
                    "dev_addr_int": dev_addr,
                    "nwk_s_key_bytes": nwk_s_key,
                    "app_s_key_bytes": app_s_key,
                    "nwk_s_key": hex_bytes(nwk_s_key),
                    "app_s_key": hex_bytes(app_s_key),
                }
            )

    if not devices:
        raise ValueError("El CSV no contiene dispositivos")

    return devices


def write_manifest(
    manifest_path: Path,
    args: argparse.Namespace,
    count: int,
    csv_path: Path,
    json_path: Path,
    header_path: Path,
) -> None:
    reproducible = args.seed is not None
    reproduce_command = None
    if reproducible:
        reproduce_command = (
            "python tools/generate_abp_devices.py "
            f"--count {count} --seed {args.seed} "
            f"--devaddr-base 0x{args.devaddr_base:08X} "
            f"--deveui-base 0x{args.deveui_base:016X}"
        )

    payload = {
        "script": Path(__file__).name,
        "version": 1,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "reproducible": reproducible,
        "count": count,
        "seed": args.seed,
        "devaddr_base": f"0x{args.devaddr_base:08X}",
        "deveui_base": f"0x{args.deveui_base:016X}",
        "device_class": args.device_class,
        "profile": args.profile,
        "lorawan_version": args.lorawan_version,
        "csv": str(csv_path),
        "json": str(json_path),
        "header": str(header_path),
        "manifest": str(manifest_path),
        "reproduce_command": reproduce_command,
    }

    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    project_root = Path(__file__).resolve().parent.parent

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--count", type=int, default=None, help="default: 10")
    parser.add_argument(
        "--devaddr-base",
        type=parse_int,
        default=None,
        help="default: 0x260C7000",
    )
    parser.add_argument(
        "--deveui-base",
        type=parse_int,
        default=None,
        help="default: 0x70B3D57ED0000001",
    )
    parser.add_argument("--out-dir", type=Path, default=project_root / "tools" / "out")
    parser.add_argument(
        "--header",
        type=Path,
        default=project_root / "include" / "MultiDeviceConfig.h",
    )
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument("--class", dest="device_class", default=None, help="default: A")
    parser.add_argument("--profile", default=None, help="default: US915")
    parser.add_argument("--lorawan-version", default=None, help="default: 1.0.3")
    parser.add_argument("--force", action="store_true")
    parser.add_argument(
        "--from-csv",
        type=Path,
        default=None,
        metavar="CSV",
        help="import an existing devices.csv and rebuild only the firmware header",
    )
    parser.add_argument(
        "--manifest",
        action="store_true",
        help="write generation.json with seed, bases and count",
    )
    parser.add_argument(
        "--manifest-path",
        type=Path,
        default=None,
        help="custom manifest path (implies --manifest)",
    )
    args = parser.parse_args()

    if args.from_csv is not None:
        generation_args = {
            "--count": args.count,
            "--devaddr-base": args.devaddr_base,
            "--deveui-base": args.deveui_base,
            "--seed": args.seed,
            "--class": args.device_class,
            "--profile": args.profile,
            "--lorawan-version": args.lorawan_version,
        }
        used = [name for name, value in generation_args.items() if value is not None]
        if used:
            parser.error("--from-csv no se puede combinar con: " + ", ".join(used))
        if args.manifest or args.manifest_path is not None:
            parser.error("--from-csv no escribe manifest")

        try:
            devices = read_devices_from_csv(args.from_csv)
        except (OSError, ValueError) as exc:
            parser.error(str(exc))

        if args.header.exists() and not args.force:
            parser.error("Ya existe el header; usa --force para sobrescribirlo")

        write_header(devices, args.header)

        print(f"Dispositivos importados: {len(devices)}")
        print(f"CSV origen: {args.from_csv}")
        print(f"Header:     {args.header}")
        print("Se importaron las credenciales existentes; no se uso semilla.")
        print("Las claves son sensibles: no versiones tools/out/ ni MultiDeviceConfig.h.")
        return 0

    count = args.count if args.count is not None else 10
    args.devaddr_base = args.devaddr_base if args.devaddr_base is not None else 0x260C7000
    args.deveui_base = args.deveui_base if args.deveui_base is not None else 0x70B3D57ED0000001
    args.device_class = args.device_class if args.device_class is not None else "A"
    args.profile = args.profile if args.profile is not None else "US915"
    args.lorawan_version = (
        args.lorawan_version if args.lorawan_version is not None else "1.0.3"
    )

    if count <= 0:
        parser.error("--count debe ser mayor que 0")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    args.header.parent.mkdir(parents=True, exist_ok=True)

    existing = [
        path
        for path in (args.out_dir / "devices.csv", args.out_dir / "devices.json", args.header)
        if path.exists()
    ]
    if existing and not args.force:
        parser.error(
            "Ya existen archivos generados; usa --force para regenerarlos "
            "(cambiaran las claves y habra que reregistrar los dispositivos)."
        )

    def derived_key(index: int, purpose: str) -> bytes:
        if args.seed is None:
            return secrets.token_bytes(16)
        material = f"phantom_multi:{args.seed}:{index}:{purpose}".encode("utf-8")
        return hashlib.sha256(material).digest()[:16]

    devices = []
    for i in range(count):
        dev_eui = (args.deveui_base + i) & 0xFFFFFFFFFFFFFFFF
        dev_addr = (args.devaddr_base + i) & 0xFFFFFFFF
        nwk_s_key = derived_key(i, "nwk")
        app_s_key = derived_key(i, "app")

        devices.append(
            {
                "index": i,
                "dev_eui": f"{dev_eui:016X}",
                "dev_addr": f"{dev_addr:08X}",
                "dev_addr_int": dev_addr,
                "nwk_s_key_bytes": nwk_s_key,
                "app_s_key_bytes": app_s_key,
                "nwk_s_key": hex_bytes(nwk_s_key),
                "app_s_key": hex_bytes(app_s_key),
                "nwk_s_enc_key": hex_bytes(nwk_s_key),
                "f_nwk_s_int_key": hex_bytes(nwk_s_key),
                "s_nwk_s_int_key": hex_bytes(nwk_s_key),
                "f_cnt_up": 0,
                "class": args.device_class,
                "profile": args.profile,
                "lorawan_version": args.lorawan_version,
            }
        )

    csv_path = args.out_dir / "devices.csv"
    json_path = args.out_dir / "devices.json"

    csv_fields = [
        "dev_eui",
        "dev_addr",
        "nwk_s_key",
        "app_s_key",
        "nwk_s_enc_key",
        "f_nwk_s_int_key",
        "s_nwk_s_int_key",
        "f_cnt_up",
        "class",
        "profile",
        "lorawan_version",
    ]

    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=csv_fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(devices)

    json_fields = [
        "index",
        "dev_eui",
        "dev_addr",
        "nwk_s_key",
        "app_s_key",
        "nwk_s_enc_key",
        "f_nwk_s_int_key",
        "s_nwk_s_int_key",
        "f_cnt_up",
        "class",
        "profile",
        "lorawan_version",
    ]
    json_devices = [
        {key: d[key] for key in json_fields}
        for d in devices
    ]

    with json_path.open("w", encoding="utf-8") as fh:
        json.dump(json_devices, fh, indent=2)

    write_header(devices, args.header)

    manifest_path = None
    if args.manifest or args.manifest_path is not None:
        manifest_path = args.manifest_path if args.manifest_path is not None else (
            args.out_dir / "generation.json"
        )
        write_manifest(
            manifest_path,
            args,
            len(devices),
            csv_path,
            json_path,
            args.header,
        )

    print(f"Dispositivos generados: {len(devices)}")
    print(f"CSV:    {csv_path}")
    print(f"JSON:   {json_path}")
    print(f"Header: {args.header}")
    if manifest_path is not None:
        print(f"Manifest: {manifest_path}")
        if args.seed is None:
            print("Aviso: sin --seed las claves no son reproducibles.")
    print("Las claves son sensibles: no versiones tools/out/ ni MultiDeviceConfig.h.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
